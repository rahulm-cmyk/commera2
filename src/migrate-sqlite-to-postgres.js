import { DatabaseSync } from 'node:sqlite';
import { existsSync } from 'node:fs';
import pg from 'pg';

const sourceFile=process.env.SQLITE_SOURCE||'data/commera2.sqlite';
if(existsSync('.env'))process.loadEnvFile('.env');
if(!process.env.DATABASE_URL)throw Error('DATABASE_URL is required. Add it to .env before migrating.');
if(!existsSync(sourceFile))throw Error(`SQLite database not found: ${sourceFile}`);

const quote=value=>`"${String(value).replaceAll('"','""')}"`;
const references=sql=>[...sql.matchAll(/REFERENCES\s+([a-z_]+)/gi)].map(match=>match[1].toLowerCase());
const postgresTableSql=sql=>sql
  .replace(/^CREATE TABLE\s+/i,'CREATE TABLE IF NOT EXISTS ')
  .replace(/\bid\s+INTEGER PRIMARY KEY\b/i,'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/\bAUTOINCREMENT\b/gi,'');

function orderedTables(tables){
  const pending=new Map(tables.map(table=>[table.name,{...table,deps:new Set(references(table.sql).filter(name=>name!==table.name))}]));
  const output=[];
  while(pending.size){
    const ready=[...pending.values()].filter(table=>[...table.deps].every(dep=>!pending.has(dep)));
    if(!ready.length)throw Error(`Could not order tables with foreign keys: ${[...pending.keys()].join(', ')}`);
    for(const table of ready){output.push(table);pending.delete(table.name);}
  }
  return output;
}

const sqlite=new DatabaseSync(sourceFile,{readOnly:true});
const tables=orderedTables(sqlite.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all());
const indexes=sqlite.prepare("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name").all().map(row=>row.sql);
const client=new pg.Client({connectionString:process.env.DATABASE_URL});

try{
  await client.connect();
  const existing=await client.query("SELECT 1 FROM information_schema.tables WHERE table_schema='public' LIMIT 1");
  if(existing.rowCount)throw Error('PostgreSQL public schema is not empty. Migration stopped to prevent overwriting data.');
  await client.query('BEGIN');
  for(const table of tables)await client.query(postgresTableSql(table.sql));
  for(const index of indexes)await client.query(index);
  for(const table of tables){
    const rows=sqlite.prepare(`SELECT * FROM ${quote(table.name)}`).all();
    if(!rows.length)continue;
    const columns=Object.keys(rows[0]);
    const sql=`INSERT INTO ${quote(table.name)} (${columns.map(quote).join(',')}) VALUES (${columns.map((_,index)=>`$${index+1}`).join(',')})`;
    for(const row of rows)await client.query(sql,columns.map(column=>row[column]));
    if(/\bid\s+INTEGER\s+PRIMARY KEY\b/i.test(table.sql))await client.query(`SELECT setval(pg_get_serial_sequence('${table.name}','id'), GREATEST(COALESCE(MAX(id),0),1), true) FROM ${quote(table.name)}`);
  }
  await client.query('COMMIT');
  console.log(`Migrated ${tables.length} tables from ${sourceFile} to PostgreSQL.`);
}catch(error){await client.query('ROLLBACK').catch(()=>{});throw error;}finally{sqlite.close();await client.end();}
