const postgresTableSql = (sql) =>
  sql
    .replace(/^CREATE TABLE\s+/i, "CREATE TABLE IF NOT EXISTS ")
    .replace(
      /\bid\s+INTEGER PRIMARY KEY\b/i,
      "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    )
    .replace(/\bAUTOINCREMENT\b/gi, "");

const postgresIndexSql = (sql) =>
  sql.replace(/^CREATE (?:UNIQUE )?INDEX\s+/i, (match) =>
    match.replace(/INDEX\s*$/i, "INDEX IF NOT EXISTS "),
  );

const schemaDependencies = (sql) =>
  [...String(sql).matchAll(/REFERENCES\s+([a-z_]+)/gi)].map((match) =>
    match[1].toLowerCase(),
  );

const orderedSchemaTables = (tables) => {
  const pending = new Map(
    tables.map((table) => [
      table.name,
      { ...table, dependencies: new Set(schemaDependencies(table.sql)) },
    ]),
  );
  const ordered = [];
  while (pending.size) {
    const ready = [...pending.values()].filter((table) =>
      [...table.dependencies].every((dependency) => !pending.has(dependency)),
    );
    if (!ready.length)
      throw new Error(
        `Could not order PostgreSQL schema tables: ${[...pending.keys()].join(", ")}`,
      );
    for (const table of ready) {
      ordered.push(table);
      pending.delete(table.name);
    }
  }
  return ordered;
};

const bootstrapEmptyPostgresSchema = (db) => {
  const existing = db
    .prepare("SELECT to_regclass('public.stores') AS stores_table")
    .get();
  if (existing?.stores_table) return;

  // The SQLite schema remains the single source of truth. Build it in memory,
  // then translate its table definitions for a brand-new PostgreSQL database.
  const template = createDatabase(":memory:");
  try {
    const tables = orderedSchemaTables(
      template
        .prepare(
          "SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
        )
        .all(),
    );
    const indexes = template
      .prepare(
        "SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name",
      )
      .all();
    for (const table of tables) db.exec(postgresTableSql(table.sql));
    for (const index of indexes) db.exec(postgresIndexSql(index.sql));
  } finally {
    template.close();
  }
};

