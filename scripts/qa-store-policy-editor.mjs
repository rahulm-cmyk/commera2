import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createDatabase } from '../src/database.js';
import { createApp } from '../src/server.js';

const require=createRequire(import.meta.url);
const {chromium}=require(process.env.QA_PLAYWRIGHT_PATH||'playwright');
process.env.DATABASE_MODE='sqlite';
const app=createApp({db:createDatabase(':memory:'),port:0,merchantAuth:false,domainSyncIntervalMs:0,otpProviders:{},googleAuthProvider:null,accountEmailProvider:null});
const store=app.service.createStore({name:'Policy connection test',slug:'policy-connection-test'});
await app.start('127.0.0.1');
const base=`http://127.0.0.1:${app.port}`,root=`/api/stores/${store.id}`,output='data/store-policy-editor-qa';
await mkdir(output,{recursive:true});
const api=async(path,method='GET',body)=>{const res=await fetch(base+path,{method,headers:{'content-type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});assert.ok(res.ok,await res.clone().text());return (res.headers.get('content-type')||'').includes('json')?res.json():res.text();};
await api(`${root}/storefront/home`,'PATCH',{bannerHeading:'Saved heading',bannerVisible:true,featuredVisible:false,featuredProductIds:[]});
const browser=await chromium.launch({headless:true,executablePath:process.env.QA_BROWSER_PATH||'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'});
const page=await browser.newPage({viewport:{width:1440,height:960},reducedMotion:'reduce'}),errors=[],failedResponses=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error'&&!message.text().startsWith('Failed to load resource:'))errors.push(message.text());});
page.on('response',response=>{if(response.status()>=400)failedResponses.push({status:response.status(),path:new URL(response.url()).pathname});});
const frame=()=>page.locator('#store-website-preview').contentFrame();
const row=type=>page.locator(`#store-policy-connections [data-policy-type="${type}"]`);
const status=async(type,value)=>{await row(type).locator('.store-policy-status').getByText(value,{exact:true}).waitFor();};
const screenshot=async(name)=>{
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  const overflow=await page.evaluate(()=>({document:document.documentElement.scrollWidth-innerWidth,settings:document.querySelector('.store-settings-area').scrollWidth-document.querySelector('.store-settings-area').clientWidth}));
  assert.ok(overflow.document<=1&&overflow.settings<=1,JSON.stringify(overflow));
  await page.screenshot({path:`${output}/${name}.png`});
};
try {
  await page.goto(`${base}/online-store/themes/current/edit`,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Banner',exact:true}).click();
  await page.locator('[name="bannerHeading"]').fill('Unsaved design stays intact');
  await page.locator('#store-home-form').evaluate(form=>window.qaHomeForm=form);
  await page.getByRole('button',{name:'Footer',exact:true}).click();
  await page.getByRole('button',{name:'Store policies',exact:true}).click();
  assert.equal(await page.locator('#store-section-title').textContent(),'Store policies');
  assert.equal(await page.locator('.store-policy-connection').count(),7);
  assert.equal(await row('shipping').getByRole('button',{name:'Publish Shipping Policy'}).isDisabled(),true);
  assert.equal(await frame().locator('nav[aria-label="Policies"]').count(),0);
  await row('shipping').getByRole('button',{name:'Edit Shipping Policy'}).click();
  await page.locator('#modal').getByRole('button',{name:'Save',exact:true}).click();
  await page.getByText('Policy Content is required',{exact:true}).waitFor();
  assert.ok(await page.locator('#modal').isVisible());
  await page.getByRole('textbox',{name:'Policy content'}).fill('Shipping information for this test store.');
  await page.locator('#modal').getByRole('button',{name:'Save',exact:true}).click();
  await page.locator('#modal').waitFor({state:'hidden'});
  await status('shipping','Draft');
  assert.equal(await page.locator('#store-home-form').evaluate(form=>form===window.qaHomeForm),true);
  assert.equal(await page.locator('[name="bannerHeading"]').inputValue(),'Unsaved design stays intact');
  assert.equal(await page.getByRole('button',{name:'Save',exact:true}).isDisabled(),false);
  assert.equal(await frame().locator('nav[aria-label="Policies"]').count(),0,'Saving a draft must not publish its link');
  const popupPromise=page.waitForEvent('popup');
  await row('shipping').getByRole('link',{name:'Preview Shipping Policy'}).click();
  const popup=await popupPromise;
  await popup.waitForLoadState('domcontentloaded');
  assert.ok((await popup.locator('body').textContent()).includes('Shipping information for this test store.'));
  await popup.close();
  await row('shipping').getByRole('button',{name:'Publish Shipping Policy'}).click();
  await status('shipping','Published');
  await api(`${root}/policies/written/privacy`,'PATCH',{title:'Privacy Policy',content:'<p>Policy changed in another tab.</p>'});
  await api(`${root}/policies/written/privacy/publish`,'POST',{});
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await status('privacy','Published');
  assert.equal(await page.locator('[name="bannerHeading"]').inputValue(),'Unsaved design stays intact');
  assert.equal(await page.locator('#store-home-form').evaluate(form=>form===window.qaHomeForm),true,'Refreshing another tab policy change must preserve the design form');
  assert.equal(await frame().getByRole('navigation',{name:'Policies',exact:true}).getByRole('link',{name:'Shipping Policy'}).getAttribute('href'),`/s/${store.slug}/policies/shipping`);
  assert.equal(await frame().getByRole('navigation',{name:'Store navigation',exact:true}).getByRole('link',{name:'Policies',exact:true}).count(),1);
  await screenshot('desktop-policy-connections');
  await page.getByRole('button',{name:'Close settings'}).click();
  await frame().getByRole('navigation',{name:'Policies',exact:true}).getByRole('link',{name:'Shipping Policy'}).click();
  assert.equal(await page.locator('#store-section-title').textContent(),'Store policies');
  await row('shipping').getByRole('button',{name:'Unpublish Shipping Policy'}).click();
  await status('shipping','Draft');
  assert.equal(await frame().getByRole('navigation',{name:'Policies',exact:true}).getByRole('link',{name:'Shipping Policy'}).count(),0);
  assert.equal(await frame().getByRole('navigation',{name:'Policies',exact:true}).getByRole('link',{name:'Privacy Policy'}).count(),1);
  await row('shipping').getByRole('button',{name:'Publish Shipping Policy'}).click();
  await status('shipping','Published');
  await row('contact').getByRole('button',{name:'Edit Contact Information'}).click();
  await page.locator('#modal').getByRole('textbox',{name:'Support Email'}).fill('support@example.com');
  await page.locator('#modal').getByRole('button',{name:'Save',exact:true}).click();
  await page.locator('#modal').waitFor({state:'hidden'});
  await status('contact','Draft');
  assert.equal(await page.locator('#store-home-form').evaluate(form=>form===window.qaHomeForm),true,'Editing contact must not rebuild the design form');
  await row('contact').getByRole('button',{name:'Publish Contact Information'}).click();
  await status('contact','Published');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.getByText('Draft saved',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Manage policies',exact:true}).click();
  await page.waitForURL(`${base}/policy`);
  assert.equal(await page.locator('[data-type="shipping"]').getByText('Published',{exact:true}).count(),1);
  await page.getByRole('button',{name:'Edit store footer',exact:true}).click();
  await page.waitForURL('**/edit?section=footer&block=policies');
  await page.locator('#store-section-title').getByText('Store policies',{exact:true}).waitFor();
  await status('shipping','Published');
  await page.reload({waitUntil:'networkidle'});
  await status('contact','Published');
  assert.equal(await page.locator('[name="bannerHeading"]').inputValue(),'Unsaved design stays intact');
  await frame().getByRole('navigation',{name:'Policies',exact:true}).getByRole('link',{name:'Shipping Policy'}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('tab',{name:'Settings'}).click();
  await screenshot('mobile-policy-connections');
  await page.getByRole('tab',{name:'Preview'}).click();
  await screenshot('mobile-footer');
  assert.deepEqual(errors,[]);
  assert.deepEqual(failedResponses,[{status:400,path:`${root}/policies/written/shipping`}],'Only the deliberately empty policy save may fail');
  console.log(JSON.stringify({passed:true,policies:7,checks:['footer block and preview selection','draft validation','policy preview','publish and unpublish sync','unsaved design preserved','other-tab updates','contact save preserved','policy management return link','save and reload','desktop and mobile layout'],screenshots:output},null,2));
} finally {await browser.close();await app.stop();}
